const licensed = (
  guideId: string,
  title: string,
  alt: string,
  photographer: string,
  filename: string,
  licenseName: string,
  licenseUrl: string,
  rationale: string,
  depiction: string,
): GuideMedia => ({
  guideId,
  src: `/images/guides/${guideId}.jpg`,
  title,
  alt,
  photographer,
  sourceUrl: `https://commons.wikimedia.org/wiki/${encodeURI(filename.replaceAll(" ", "_"))}`,
  licenseName,
  licenseUrl,
  rightsBasis: "documented_license",
  rightsCheckedOn: "2026-10-21",
  visualReview: { outcome: "approved", checkedOn: "2026-10-21", rationale },
  depiction: `${depiction} Resized and responsively cropped under the stated licence. No EA attendance, endorsement or future conditions are implied.`,
});
